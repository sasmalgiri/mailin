//  RAR 7.0: archives written by RARLAB's rar 7.23 for macOS (trial, kept
//  outside the repository) with RAR 7.0 features — compression algorithm
//  version 1 (dictionaries over 4 GiB, non-power-of-two sizes), solid,
//  multi-volume, encrypted data and encrypted headers (Fixtures/rar7,
//  MANIFEST.md). Oracle: the CRC-32 rar wrote into every header (checked by
//  the extractor) and the SHA-256 of the synthetic text members, recorded
//  when the members were generated. Before the rar7 patch every member here
//  was refused ("RAR 7.0 compression not opened", or a dictionary over
//  64 MiB).
//
//  RAR 1.5 / 2.0: real archives from public test suites (junrar, rarfile;
//  Fixtures/rar-legacy, MANIFEST.md). Oracle: the CRC-32 in each header,
//  and — for the WAV recording that four of them hold — the same bytes as
//  libarchive's RAR 2.9 decode of the RAR 3 archive of the same file.
//  Before RARLegacyDecoder.swift every compressed member was refused.
//

import XCTest
import CryptoKit
@testable import ArchiveCore

final class RAR7AndLegacyRARTests: XCTestCase {

    static let rar7 = URL(fileURLWithPath: #filePath).deletingLastPathComponent().appendingPathComponent("Fixtures/rar7", isDirectory: true)
    static let legacy = URL(fileURLWithPath: #filePath).deletingLastPathComponent().appendingPathComponent("Fixtures/rar-legacy", isDirectory: true)

    /// SHA-256 of the synthetic members (MANIFEST.md, generated by gen.py).
    static let memberSHA: [String: String] = [
        "member1.txt": "4735499765e8598998a2c88f69274f89617cd9a28decc49bcca0639175111f8b",
        "member2.txt": "2a5a5f9851f68d977c6350ff8b955db208cce83c9f5033bcc4660b25f743d10d",
        "member3.txt": "24bfcca2844807c8d49f7738f252fbb32495a86f7067df72ecf2543c3981867d",
        "all.txt": "e4e9a9f448ed21e40f1181612675518638984f2e1563f9cfbc7831aeec9bec7e",
    ]

    private var scratch: URL!

    override func setUpWithError() throws {
        scratch = FileManager.default.temporaryDirectory.appendingPathComponent("rar7-legacy-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: scratch, withIntermediateDirectories: true)
    }
    override func tearDown() {
        try? FileManager.default.removeItem(at: scratch)
        super.tearDown()
    }

    private static func sha256(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }

    private func extract(_ extractor: RARReader.Extractor, _ name: String, file: StaticString = #filePath, line: UInt = #line) throws -> Data {
        let member = try XCTUnwrap(extractor.archive.members.first { $0.name == name }, name, file: file, line: line)
        XCTAssertNil(extractor.refusal(for: member), name, file: file, line: line)
        let out = scratch.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: out) }
        try extractor.extract(member, to: out)
        return try Data(contentsOf: out)
    }

    private func assertMember(_ extractor: RARReader.Extractor, _ name: String, file: StaticString = #filePath, line: UInt = #line) throws {
        let data = try extract(extractor, name, file: file, line: line)
        XCTAssertEqual(Self.sha256(data), Self.memberSHA[name], name, file: file, line: line)
    }

    // MARK: - RAR 7.0

    func testRAR7_version1MembersAndLargeDictionariesDecode() throws {
        let v1 = try RARReader.Extractor(url: Self.rar7.appendingPathComponent("rar7_v1_dict5g.rar"))
        let member = try XCTUnwrap(v1.archive.members.first)
        XCTAssertEqual(member.algorithmVersion, 1)
        XCTAssertEqual(member.methodName, "RAR7.0 method 3")
        XCTAssertEqual(member.dictionaryBytes, 5 << 30, "128 KiB << 15 plus 8/32: the non-power-of-two 5 GiB rar was asked for")
        XCTAssertFalse(member.rar5CompatibleAlgorithm)
        XCTAssertEqual(member.decoderWindowBytes, 8 << 20, "a 174 KB member needs an 8 MiB window, not 5 GiB")
        try assertMember(v1, "member1.txt")

        // RAR 5.0 algorithm, 1 GiB dictionary: refused before (over 64 MiB).
        let big = try RARReader.Extractor(url: Self.rar7.appendingPathComponent("rar5_v0_dict1g.rar"))
        XCTAssertEqual(big.archive.members.first?.algorithmVersion, 0)
        XCTAssertEqual(big.archive.members.first?.dictionaryBytes, 1 << 30)
        try assertMember(big, "member1.txt")

        // The whole path the app uses: children decoded, text read.
        let result = try DocumentTextExtractor.extract(fileURL: Self.rar7.appendingPathComponent("rar7_v1_dict5g.rar"), kind: .rar, logicalName: "x.rar")
        let child = try XCTUnwrap(result.children.first { $0.path == "member1.txt" })
        XCTAssertEqual(child.state, .extracted, child.note ?? "")
        XCTAssertEqual(child.sha256, Self.memberSHA["member1.txt"])
    }

    func testRAR7_solidStreamsDecodeInAndOutOfOrder() throws {
        // member1 in the RAR 7.0 algorithm (5 GiB dictionary), members 2–3 appended in RAR 5.0 (1 MiB) continuing its stream.
        let url = Self.rar7.appendingPathComponent("rar7_v1_then_v0_solid.rar")
        let mixed = try RARReader.Extractor(url: url)
        XCTAssertTrue(mixed.archive.isSolid)
        XCTAssertEqual(mixed.archive.members.map(\.algorithmVersion), [1, 0, 0])
        for name in ["member1.txt", "member2.txt", "member3.txt"] { try assertMember(mixed, name) }
        let backwards = try RARReader.Extractor(url: url)
        for name in ["member3.txt", "member1.txt", "member2.txt"] { try assertMember(backwards, name) }

        // All RAR 7.0, a 4.5 GiB dictionary kept by a 4.6 GB (sparse, zero) last member, split over three volumes.
        let parts = (1...3).map { Self.rar7.appendingPathComponent("rar7_v1_solid_volumes.part0000\($0).rar") }
        let padded = try RARReader.Extractor(url: parts[0], siblings: parts.dropFirst().map { .init(url: $0) })
        XCTAssertTrue(padded.isVolumeSet)
        XCTAssertEqual(padded.archive.members.map(\.name), ["member1.txt", "member2.txt", "member3.txt", "zz_padding.bin"])
        XCTAssertEqual(padded.archive.members.map(\.algorithmVersion), [1, 1, 1, 1])
        XCTAssertEqual(padded.archive.members.first?.dictionaryBytes, 4_831_838_208)
        for name in ["member2.txt", "member1.txt", "member3.txt"] { try assertMember(padded, name) }
        // The last member's window - 8 GiB for 4.6 GB of stream - is over the device limit: named, never allocated.
        let pad = try XCTUnwrap(padded.archive.members.last)
        XCTAssertEqual(pad.lastVolume, 2)
        XCTAssertEqual(pad.decoderWindowBytes, 8 << 30)
        let reason = try XCTUnwrap(padded.refusal(for: pad))
        XCTAssertEqual(reason, "needs a 8589934592-byte RAR decoding window for its 4831838208-byte dictionary, over this device's \(RARReader.maxDecoderWindowBytes)-byte limit")
        XCTAssertThrowsError(try padded.extract(pad, to: scratch.appendingPathComponent("pad"))) { error in
            XCTAssertEqual(error as? RARReader.ReadError, .compressionNotOpened(member: "zz_padding.bin", reason: reason))
        }
    }

    func testRAR7_multiVolumeAndEncryptedArchivesOpen() throws {
        // Written from a pipe (rar -si) into volumes: the first volumes' headers carry no unpacked size
        // (rar cannot go back to them), which the vendored decoder needs - named, not guessed.
        let parts = (1...3).map { Self.rar7.appendingPathComponent("rar7_v1_pipe_volumes.part\($0).rar") }
        let set = try RARReader.Extractor(url: parts[0], siblings: parts.dropFirst().map { .init(url: $0) })
        XCTAssertTrue(set.isVolumeSet)
        XCTAssertEqual(set.archive.members.map(\.name), ["all.txt"])
        XCTAssertEqual(set.archive.members[0].lastVolume, 2)
        XCTAssertEqual(set.refusal(for: set.archive.members[0]), "the unpacked size is not recorded in the header (the vendored decoder needs it)")

        let encrypted = try RARReader.Extractor(url: Self.rar7.appendingPathComponent("rar7_v1_encrypted.rar"), password: "mailin7")
        XCTAssertTrue(encrypted.archive.members[0].isEncrypted)
        XCTAssertEqual(encrypted.archive.members[0].algorithmVersion, 1)
        try assertMember(encrypted, "member2.txt")
        let wrong = try RARReader.Extractor(url: Self.rar7.appendingPathComponent("rar7_v1_encrypted.rar"), password: "nope")
        XCTAssertThrowsError(try wrong.extract(wrong.archive.members[0], to: scratch.appendingPathComponent("w"))) {
            XCTAssertEqual($0 as? RARReader.ReadError, .wrongPassword(member: "member2.txt"))
        }

        let headers = Self.rar7.appendingPathComponent("rar7_v1_encrypted_headers.rar")
        XCTAssertThrowsError(try RARReader.Extractor(url: headers)) { XCTAssertEqual($0 as? RARReader.ReadError, .encryptedHeaders) }
        let opened = try RARReader.Extractor(url: headers, password: "mailin7")
        XCTAssertTrue(opened.archive.headersEncrypted)
        try assertMember(opened, "member3.txt")
    }

    func testRAR7_windowRuleAndRefusals() throws {
        func member(_ name: String, size: Int64, dictionary: Int64, version: Int = 0, method: Int = 3, known: Bool = true) -> RARReader.Member {
            RARReader.Member(name: name, unpackedSize: size, packedSize: 1, crc32: nil, method: method, algorithmVersion: version, isDirectory: false,
                             isEncrypted: false, isSolid: false, isSplitBefore: false, isSplitAfter: false, isSymlink: false, hostOS: "Unix",
                             dataOffset: 0, format: .rar5, dictionaryBytes: dictionary, sizeIsKnown: known)
        }
        var plain = RARReader.Archive(format: .rar5)
        plain.members = [member("small", size: 1000, dictionary: 32 << 20), member("tiny-dict", size: 1 << 20, dictionary: 128 << 10),
                         member("mid", size: 20 << 20, dictionary: 1 << 30), member("capped", size: 900 << 20, dictionary: 256 << 20),
                         member("stored", size: 5, dictionary: 1 << 30, method: 0)]
        RARReader.assignDecoderWindows(&plain)
        XCTAssertEqual(plain.members.map(\.decoderWindowBytes), [8 << 20, 128 << 10, 32 << 20, 256 << 20, nil])

        var solid = plain
        solid.isSolid = true
        RARReader.assignDecoderWindows(&solid)
        // Stream sums 1000 → 1 MiB+ → 21 MiB+ → 921 MiB+ ; never shrinking; capped by each declared dictionary.
        XCTAssertEqual(solid.members.map(\.decoderWindowBytes), [8 << 20, 8 << 20, 32 << 20, 256 << 20, nil])

        XCTAssertEqual(member("v2", size: 10, dictionary: 1 << 20, version: 2).compressionRefusal,
                       "RAR compression algorithm version 2 not opened (RAR 5.0 and 7.0 are read)")
        XCTAssertEqual(member("pipe", size: 10, dictionary: 1 << 20, known: false).compressionRefusal,
                       "the unpacked size is not recorded in the header (the vendored decoder needs it)")
        var huge = member("huge", size: 10, dictionary: 64 << 30, version: 1)
        huge.decoderWindowBytes = 64 << 30
        XCTAssertTrue(huge.compressionRefusal?.contains("over this device's") == true)
        XCTAssertEqual(RARReader.maxDecoderDictionaryBytes, RARReader.maxDecoderWindowBytes)
        XCTAssertLessThanOrEqual(RARReader.maxDecoderWindowBytes, 4 << 30)
    }

    // MARK: - RAR 1.5 and RAR 2.0

    /// The WAV in the junrar archives, decoded by libarchive from the RAR 2.9 archive of the same file.
    private func referenceWAV() throws -> Data {
        let rar3 = try RARReader.Extractor(url: Self.legacy.appendingPathComponent("BoatModernEnglish-regular-unpack30.rar"))
        XCTAssertEqual(rar3.archive.members.first?.algorithmVersion, 29)
        return try extract(rar3, "BoatModernEnglish.wav")
    }

    func testREAL_rar15MembersDecode() throws {
        let wav = try referenceWAV()
        XCTAssertEqual(wav.count, 56464)
        XCTAssertEqual(ZIPArchiveReader.CRC32.checksum(wav), 0x82D2ED89)
        for (file, wavName, licenceName) in [("BoatModernEnglish-regular-unpack15-dos.rar", "BOATMO~1.WAV", "LICENSE.TXT"),
                                             ("BoatModernEnglish-regular-unpack15-win.rar", "BoatModernEnglish.wav", "LICENSE.txt")] {
            let x = try RARReader.Extractor(url: Self.legacy.appendingPathComponent(file))
            XCTAssertEqual(x.archive.members.map(\.algorithmVersion), [15, 15], file)
            XCTAssertEqual(x.archive.members.map(\.method), [5, 5], file)
            XCTAssertEqual(try extract(x, wavName), wav, file)
            let licence = String(decoding: try extract(x, licenceName), as: UTF8.self)
            XCTAssertTrue(licence.hasPrefix("UofG Language Modules, CC BY-SA 4.0"), licence)
        }
        // rarfile's RAR 1.5 archive (written by RAR 1.5x for DOS): the compressed member, CRC-32 0xE27F07A9 checked.
        let comment = try RARReader.Extractor(url: Self.legacy.appendingPathComponent("rar15-comment.rar"))
        let file1 = try XCTUnwrap(comment.archive.members.first { $0.name == "FILE1.TXT" })
        XCTAssertEqual(file1.algorithmVersion, 15)
        XCTAssertEqual(file1.method, 3)
        XCTAssertEqual(ZIPArchiveReader.CRC32.checksum(try extract(comment, "FILE1.TXT")), 0xE27F07A9)
    }

    func testREAL_rar20MembersDecode_includingMultimediaAudio() throws {
        let wav = try referenceWAV()
        let regular = try RARReader.Extractor(url: Self.legacy.appendingPathComponent("BoatModernEnglish-regular-unpack20.rar"))
        XCTAssertEqual(regular.archive.members.first?.algorithmVersion, 20)
        XCTAssertEqual(try extract(regular, "BoatModernEnglish.wav"), wav)

        // RAR 2.0 multimedia compression (-mm): the audio predictor's blocks.
        let audio = try RARReader.Extractor(url: Self.legacy.appendingPathComponent("BoatModernEnglish-audio-text-unpack20.rar"))
        XCTAssertEqual(audio.archive.members.first?.algorithmVersion, 20)
        XCTAssertEqual(try extract(audio, "BoatModernEnglish.wav"), wav)

        // rarfile's RAR 2.x Unix archive: 4 bytes in 17, CRC-32 0x7E3265A8.
        let owner = try RARReader.Extractor(url: Self.legacy.appendingPathComponent("rar2-unix-owner.rar"))
        XCTAssertEqual(owner.archive.members.first?.algorithmVersion, 20)
        XCTAssertEqual(ZIPArchiveReader.CRC32.checksum(try extract(owner, "file.txt")), 0x7E3265A8)

        // Through the attachment path: no "not opened" note any more.
        let result = try DocumentTextExtractor.extract(fileURL: Self.legacy.appendingPathComponent("BoatModernEnglish-audio-text-unpack20.rar"),
                                                       kind: .rar, logicalName: "boat.rar")
        let child = try XCTUnwrap(result.children.first { $0.path == "BoatModernEnglish.wav" })
        XCTAssertNotEqual(child.state, .failed, child.note ?? "")
        XCTAssertFalse(child.note?.contains("RAR") == true, child.note ?? "")
        XCTAssertEqual(child.sha256, Self.sha256(wav))
    }

    func testRAR15And20_solidAfterFirstRefused_hostileFileNeverTraps() throws {
        let x = try RARReader.Extractor(url: Self.legacy.appendingPathComponent("v20-solid-negative-backref.rar"))
        XCTAssertEqual(x.archive.members.map(\.name), ["f0", "f1"])
        XCTAssertEqual(x.refusal(for: x.archive.members[1]),
                       "RAR 2.0 solid member after the first not opened (no real solid RAR 1.5/2.0 archive was available to verify the decoder on)")
        // f0 is junrar's hostile stream: it decodes to something or fails, never traps.
        _ = try? x.extract(x.archive.members[0], to: scratch.appendingPathComponent("f0"))
        XCTAssertEqual(RARReader.version, 4)
    }

    func testRAR15And20_decoderFuzz150MutationsNeverTrap() throws {
        let seeds = ["BoatModernEnglish-regular-unpack15-win.rar", "BoatModernEnglish-regular-unpack20.rar",
                     "BoatModernEnglish-audio-text-unpack20.rar"].map { Self.legacy.appendingPathComponent($0) }
        var generator = SystemRandomNumberGenerator()
        var outcomes: [String: Int] = [:]
        for round in 0..<150 {
            var bytes = [UInt8](try Data(contentsOf: seeds[round % seeds.count]))
            for _ in 0..<Int.random(in: 1...8, using: &generator) {
                bytes[Int.random(in: 60..<bytes.count, using: &generator)] = UInt8.random(in: 0...255, using: &generator)
            }
            if round % 7 == 0 { bytes.removeLast(Int.random(in: 1...4000, using: &generator)) }
            let mutated = scratch.appendingPathComponent("fuzz-\(round).rar")
            try Data(bytes).write(to: mutated)
            do {
                let extractor = try RARReader.Extractor(url: mutated)
                for member in extractor.archive.members where !member.isDirectory {
                    let out = scratch.appendingPathComponent("out-\(round)")
                    do { try extractor.extract(member, to: out, maxOutputBytes: 1 << 22); outcomes["read", default: 0] += 1 }
                    catch { outcomes["member error", default: 0] += 1 }
                    try? FileManager.default.removeItem(at: out)
                }
            } catch { outcomes["open error", default: 0] += 1 }
            try? FileManager.default.removeItem(at: mutated)
        }
        XCTAssertGreaterThan(outcomes["member error", default: 0], 0, "\(outcomes)")
    }
